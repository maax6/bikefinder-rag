#!/usr/bin/env python3
"""Freeze collected fiches without writing to the live crawl or contacting sources.

Rule references are silver evidence labels, not ground truth. Manually audited
gold annotations are a separate file and are not generated by this program.
"""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import sqlite3
import unicodedata

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = ROOT / "data/technical/hybrid-poc"
SEED = 20261010
ALIASES = {
    "IMU": ["imu", "centrale inertielle"],
    "TPMS": ["tpms", "surveillance de la pression des pneus"],
    "modes de conduite": ["modes de conduite", "mode de conduite"],
    "contrôle de traction": ["controle de traction", "traction control"],
    "ride by wire": ["ride by wire", "ride-by-wire"],
}


def fingerprint(value):
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True,
                                     separators=(",", ":")).encode()).hexdigest()


def fold(value):
    return " ".join("".join(ch for ch in unicodedata.normalize("NFKD", value)
                            if not unicodedata.combining(ch)).casefold().split())


def row_text(row):
    return f"{row['label']} : {row['value']}" if row.get("label") else row["value"]


def mentions(text, equipment):
    text = fold(text)
    values = ALIASES.get(equipment, [fold(equipment)])
    return any(re.search(r"(?<!\w)" + re.escape(fold(term)) + r"(?!\w)", text)
               for term in values)


def target_passages(record, equipment, negative=False):
    """All target rows across all sections, including target-bearing tariffs.

    Controls show the equipment and braking sections plus tariffs; controls are
    chosen only after verifying ABS is absent from every technical source row.
    Row ids resolve into the same immutable fiche, preventing scope mixing.
    """
    explicit = {(e["section"], e["text"]) for e in record.get("equipment_evidence", [])
                if e["term"] == equipment}
    result = []
    for i, row in enumerate(record["spec_rows"]):
        text = row_text(row)
        selected = (row["section"], text) in explicit or mentions(text, equipment)
        if negative:
            selected = row["section"] in {"Équipement de série", "Train avant", "Train arrière", "Tarifs"}
        if selected:
            result.append({"id": f"{record['id']}:row:{i}", "section": row["section"], "text": text})
    # Legacy parser changes could have evidence rows that lack a matching spec row.
    existing = {(p["section"], p["text"]) for p in result}
    for section, text in sorted(explicit - existing):
        result.append({"id": f"{record['id']}:evidence:{fingerprint([section, text])[:12]}",
                       "section": section, "text": text})
    return result


def silver_reference(equipment, passages, negative=False):
    if negative:
        return "unknown", "silver_no_mention", "No ABS anywhere in the frozen technical rows; absence of mention is not absence of fitment."
    technical = [p for p in passages if p["section"] != "Tarifs"]
    if not technical:
        return "unknown", "silver_tariff_only", "A priced variant does not establish whole-fiche equipment fitment or technical market."
    text = fold(" ; ".join(p["text"] for p in technical))
    if equipment == "ride by wire" and "selectio" in text:
        return None, "review_required", "Truncated source wording; independent audit required."
    if equipment == "Assistance au freinage" and re.search(r":\s*sans\s*$", text):
        return "explicitly_absent", "silver_explicit_absence", "Explicit sans applies to the requested assistance field."
    if re.search(r"(?:sans|absence d[e']?|non equipe|pas d[e']?)\s*" + re.escape(fold(equipment)), text):
        return "explicitly_absent", "silver_explicit_absence", "Target-specific explicit negative wording."
    # Mixed equipment lists have uncertain modifier scope. Do not manufacture
    # a gold label by applying a regex to all terms in a compound list.
    equipment_names = [name for name in ("ABS", "CBS", "TCS") if mentions(text, name)]
    if "en option" in text and len(equipment_names) > 1:
        if "cbs de serie - abs en option" in text:
            status = "optional" if equipment == "ABS" else "standard" if equipment == "CBS" else None
            return status, "silver_explicit_separate_clauses", "Separately qualified CBS and ABS clauses; audit remains independent."
        return None, "review_required", "Compound equipment list: option modifier scope requires independent interpretation."
    statuses = set()
    for passage in technical:
        value = fold(passage["text"])
        if "en option" in value:
            statuses.add("optional")
        elif "de serie" in value or "en serie" in value:
            statuses.add("standard")
        elif passage["section"] == "Équipement de série":
            statuses.add("standard")
        elif equipment == "marche arrière":
            statuses.add("standard")
        else:
            statuses.add("unknown")
    if len(statuses) > 1:
        return None, "review_required", "Conflicting fitment evidence across source rows."
    status = next(iter(statuses))
    if status == "optional":
        kind, note = "silver_explicit_option", "Explicit optional wording overrides a series heading."
    elif "de serie" in text or "en serie" in text:
        kind, note = "silver_explicit_standard", "Explicit series wording in the target text."
    elif equipment == "marche arrière":
        kind, note = "silver_present_specification", "Transmission specification explicitly lists reverse gear."
    else:
        kind, note = "silver_section_assumption", "Unqualified equipment listing under the series heading; source-schema assumption, not audited truth."
    return status, kind, note


def template_key(equipment, passages, negative=False):
    rows = []
    for passage in passages:
        text = fold(passage["text"])
        text = re.sub(r"\d+(?:[.,]\d+)?", "#", text)
        text = re.sub(r"(?:#\s*)+", "# ", text).strip()
        rows.append([fold(passage["section"]), text])
    return fingerprint([equipment, rows, "negative" if negative else "mention"])


def make_case(record, equipment, negative=False):
    passages = target_passages(record, equipment, negative=negative)
    status, kind, note = silver_reference(equipment, passages, negative=negative)
    decision_state = {"equipment": equipment, "passages": [{"section": p["section"], "text": p["text"]} for p in passages]}
    family = template_key(equipment, passages, negative=negative)
    return {
        "id": fingerprint([record["id"], equipment])[:20],
        "object_id": record["id"], "source_url": record["url"],
        "identity": record["identity"], "equipment": equipment, "passages": passages,
        "expected": {"status": status, "market": "unknown"},
        "reference_kind": kind, "reference_note": note,
        "split": "dev" if int(fingerprint([SEED, family])[:8], 16) % 100 < 25 else "test",
        "template_key": family, "decision_input_key": fingerprint(decision_state),
        "grouping_key": fingerprint(decision_state), "negative_control": negative,
    }


def choose_controls(records, count):
    if count == 0:
        return []
    buckets = defaultdict(list)
    for record in records:
        if any(mentions(row_text(row), "ABS") for row in record["spec_rows"]):
            continue
        if any(e["term"] == "ABS" for e in record.get("equipment_evidence", [])):
            continue
        buckets[(record["brand"], record["year"] // 10)].append(record)
    for bucket in buckets.values():
        bucket.sort(key=lambda r: fingerprint([SEED, r["id"]]))
    selected = []
    for depth in range(max(map(len, buckets.values()), default=0)):
        for key in sorted(buckets):
            if depth < len(buckets[key]):
                selected.append(buckets[key][depth])
                if len(selected) >= count:
                    return selected
    return selected


def exclude_legacy_templates(cases):
    """Previously observed pilot templates are development regressions only."""
    previous = ROOT / "data/technical/jev-poc/cases.json"
    urls = {c.get("url") for c in json.loads(previous.read_text())} if previous.exists() else set()
    families = {c["template_key"] for c in cases if c["source_url"] in urls}
    for case in cases:
        case["legacy_regression"] = case["source_url"] in urls
        if case["template_key"] in families:
            case["split"] = "dev"
            case["split_note"] = "Template family appeared in the previous nine-case pilot."


def write_json(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def prepare(source, output, control_count):
    if output.resolve() == source.parent.resolve() or source.parent.resolve() in output.resolve().parents:
        raise ValueError("POC output must be isolated from the live crawl directory")
    if control_count < 0:
        raise ValueError("Control count must be nonnegative")
    if (output / "dataset.json").exists():
        raise FileExistsError("This output already contains a frozen dataset. Choose a new --out to preserve benchmark provenance.")
    output.mkdir(parents=True, exist_ok=True)
    created_at = datetime.now(timezone.utc).isoformat()
    connection = sqlite3.connect(source.resolve().as_uri() + "?mode=ro", uri=True, timeout=2)
    try:
        connection.execute("PRAGMA query_only=ON")
        connection.execute("BEGIN")
        rows = connection.execute("SELECT url, result FROM pages WHERE state='success' ORDER BY ordinal,url").fetchall()
        states = dict(connection.execute("SELECT state,count(*) FROM pages GROUP BY state"))
        connection.rollback()
    finally:
        connection.close()
    records = []
    for url, payload in rows:
        record = json.loads(payload)
        record.update(id=fingerprint(url)[:16], source_url=url, name=record["identity"]["raw_name"],
                      brand=record["identity"]["brand"], model=record["identity"]["model"],
                      year=record["identity"]["year"], equipment_mentions=record.get("equipment_evidence", []))
        records.append(record)
    passages = [{"id": f"{record['id']}:section:{i}", "object_id": record["id"],
                 "section": section["section"], "text": section["text"], "source_url": record["url"]}
                for record in records for i, section in enumerate(record["technical_sections"])]
    dataset = {"schema_version": "hybrid-poc-v1", "created_at": created_at,
               "source": {"path": str(source.resolve()), "connection": "SQLite URI mode=ro + PRAGMA query_only; short read transaction",
                          "states_at_freeze": states, "external_requests": 0},
               "records": records, "passages": passages}
    cases = [make_case(record, equipment) for record in records
             for equipment in sorted({e["term"] for e in record.get("equipment_evidence", [])})]
    cases += [make_case(record, "ABS", negative=True) for record in choose_controls(records, control_count)]
    exclude_legacy_templates(cases)
    groups = defaultdict(list)
    for case in cases:
        groups[case["grouping_key"]].append(case)
    decision_groups = [{"key": key, "representative_id": group[0]["id"],
                        "case_ids": [case["id"] for case in group],
                        "object_ids": sorted({case["object_id"] for case in group}),
                        "multiplicity": len(group), "split": group[0]["split"],
                        "template_key": group[0]["template_key"]}
                       for key, group in groups.items()]
    write_json(output / "dataset.json", dataset)
    write_json(output / "cases.json", cases)
    write_json(output / "decision_groups.json", decision_groups)
    unique_evidence = {(e["term"], e["section"], e["text"]) for r in records for e in r.get("equipment_evidence", [])}
    manifest = {
        "schema_version": "hybrid-poc-v1", "created_at": created_at, "seed": SEED,
        "source": dataset["source"], "object_count": len(records), "section_passage_count": len(passages),
        "year_min": min(r["year"] for r in records), "year_max": max(r["year"] for r in records),
        "brands": dict(Counter(r["brand"] for r in records).most_common()),
        "equipment_evidence_rows": sum(len(r.get("equipment_evidence", [])) for r in records),
        "unique_equipment_evidence_strings": len(unique_evidence),
        "equipment_counts": dict(Counter(e["term"] for r in records for e in r.get("equipment_evidence", [])).most_common()),
        "equipment_object_cases": sum(not c["negative_control"] for c in cases),
        "negative_controls": sum(c["negative_control"] for c in cases), "cases": len(cases),
        "unique_decision_inputs": len(groups), "unique_template_families": len({c["template_key"] for c in cases}),
        "silver_reference_kinds": dict(Counter(c["reference_kind"] for c in cases)),
        "silver_status_counts": dict(Counter(c["expected"]["status"] or "unlabelled_review_required" for c in cases)),
        "case_splits": dict(Counter(c["split"] for c in cases)),
        "unique_input_splits": dict(Counter(g["split"] for g in decision_groups)),
        "template_splits": dict(Counter({c["template_key"]: c["split"] for c in cases}.values())),
        "reference_policy": "Rules are silver labels, never truth. Compound scopes and truncations have null status and need independent audit. Gold lives in gold_annotations.json and is not generated by this program.",
        "dedup_policy": "Classification inputs omit identity. Exact equipment+ordered(section,text) inputs share one API decision; weighted source cases and unique input metrics must both be reported. Identity and source are retained for scope validation and SQL only.",
        "split_policy": "Deterministic dev/test split by normalized text template (numeric values normalized), seeded 20261010. Identical/normalized template families cannot cross splits. All template families appearing on prior nine-pilot source URLs are forced to dev.",
        "dataset_sha256": hashlib.sha256((output / "dataset.json").read_bytes()).hexdigest(),
        "cases_sha256": hashlib.sha256((output / "cases.json").read_bytes()).hexdigest(),
    }
    write_json(output / "manifest.json", manifest)
    print(json.dumps({k: manifest[k] for k in ["object_count", "equipment_evidence_rows", "unique_equipment_evidence_strings", "cases", "unique_decision_inputs", "unique_template_families", "silver_reference_kinds", "case_splits"]}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=ROOT / "data/technical/motoplanete/crawl.sqlite3")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--controls", type=int, default=200)
    args = parser.parse_args()
    prepare(args.source, args.out, args.controls)
